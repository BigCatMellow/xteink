#!/usr/bin/env python3
"""Build the collection from canonical games; no hand-forked game engines."""
import argparse
import hashlib
import json
import re
from pathlib import Path

from sync_game_ui import GAMES, ROOT, project_path

HUB = project_path('games-hub')
SHARED = {'ui_core': 'game_ui', 'theme': 'game_theme', 'game_style': 'game_style',
          'typefaces': 'typefaces', 'font_data': 'font_data', 'font_license': 'font_license',
          'puzzle_store': 'puzzle_store'}
DESCRIPTIONS = {'line-lift': 'Untangle crossing rods', 'summit-putt': 'A little mountain golf', 'link-grid': 'Connect every tile', 'ink-runes': 'Discover the hidden runes', 'lantern-logic': 'Light up a logic puzzle', 'ray-vault': 'Guide the beam home', 'island-links': 'Bridge a quiet archipelago', 'oddity-hunt': 'Find five hidden objects', 'word-hunt': 'Find words, keep exploring', 'nonogram': 'Reveal a picture in ink', 'word-bridge': 'Change a word, one letter', 'rectangle-rooms': 'Divide the board into rooms', 'sudoku': 'Nine numbers, endless puzzles', 'crown-fields': 'One crown in every region', 'ten-pairs': 'Pair numbers, clear the sheet', 'quiet-mines': 'Deduce every safe square', 'sum-cross': 'Solve the crossing sums'}


def outputs():
    result = {}
    for name, source in SHARED.items():
        result[name + '.lua'] = (ROOT / 'shared' / (source + '.lua')).read_bytes()
    for source in (HUB / 'src').glob('*.lua'):
        result[source.name] = source.read_bytes()
    result['import_expected.lua'] = b'return false -- Public builds never contain personal saves.\n'
    catalogue = []
    assert set(DESCRIPTIONS) == set(GAMES), "Every registered game needs a hub entry"
    for game in GAMES:
        description = DESCRIPTIONS[game]
        folder = project_path(game) / 'app'
        manifest = json.loads((folder / 'manifest.json').read_text())
        appid = manifest['app_id']
        parts = ['-- Generated by scripts/build_game_hub.py; edit the source game.\n',
                 'local native_require=require\nlocal native_G=_G\nreturn function(test)\n',
                 'local __TEST=test\nlocal _G=setmetatable({__TEST=test},{__index=native_G})\n',
                 'local factories,loaded={},{}\nlocal require\n',
                 "require=function(name)\n if loaded[name]~=nil then return loaded[name] end\n",
                 ' local f=factories[name]\n if not f then return native_require(name) end\n',
                 ' local v=f();if v==nil then v=true end;loaded[name]=v;return v\nend\n']
        digest = hashlib.sha256()
        for source in sorted(folder.glob('*.lua')):
            digest.update(source.name.encode() + b'\0' + source.read_bytes())
            if source.stem in SHARED or source.stem == 'ui':
                continue
            if source.stem == 'index':
                continue
            parts.append('factories[' + json.dumps(source.stem) + ']=function()\n' + source.read_text() + '\nend\n')
        index = (folder / 'index.lua').read_text()
        index = re.sub(r'^function (on_\w+)\(', r'local function \1(', index, flags=re.M)
        parts.append(index)
        parts.append('\nreturn {load=on_load,draw=on_draw,input=on_input,leave=on_leave,api=test and test.api,require=require}\nend\n')
        result['game_' + appid + '.lua'] = ''.join(parts).encode()
        catalogue.append('{id=%s,name=%s,version=%s,description=%s,source=%s}' % tuple(
            json.dumps(v) for v in (appid, manifest['display_name'], manifest['version'], description, digest.hexdigest())))
    result['catalogue.lua'] = ('-- Generated source versions and fingerprints.\nreturn {\n' + ',\n'.join(catalogue) + '\n}\n').encode()
    assert len(result) <= 32, f'Firmware code-file limit exceeded: {len(result)}'
    size = 16 + 104 * len(result) + sum(map(len, result.values()))
    assert size <= 0x80000, f'Firmware code-byte limit exceeded: {size}'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = outputs()
    app = HUB / 'app'
    assert not (app / 'data').exists(), 'Public hub source must not contain private save imports'
    bad = []
    for name, data in result.items():
        target = app / name
        if args.check:
            if not target.exists() or target.read_bytes() != data:
                bad.append(name)
        else:
            target.write_bytes(data)
    stale = {p.name for p in app.glob('*.lua')} - result.keys()
    assert not stale, f'Unexpected hub code: {stale}'
    assert not bad, 'Hub needs rebuild: ' + ', '.join(bad)
    size = 16 + 104 * len(result) + sum(map(len, result.values()))
    print(f'Games Hub: {len(GAMES)} games, {len(result)}/32 code files, {size:,}/524,288 container bytes')


if __name__ == '__main__':
    main()
