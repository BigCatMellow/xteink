#!/usr/bin/env python3
"""Bake licensed Poppins/Inter into small 1-bit PNG glyphs and exact metrics.

The firmware cannot crop runtime images, so glyphs are independent PNGs.
Only their tight ink bounds are stored. Per-glyph images stay inside their
integer advance and the font's declared line height. No TTF is loaded by Lua.
"""
import argparse
import hashlib
from io import BytesIO
import json
import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT/'assets/fonts/game-ui'
ASCII = ''.join(chr(c) for c in range(32, 127) if chr(c) not in '[]{}|')
CONTROLS = ASCII
HEADINGS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 !?-:.'
SPECS = {
    'small': ('Inter.ttf', 20, 500, ASCII, 0),
    'medium': ('Poppins-Medium.ttf', 24, 500, CONTROLS, 0),
    'large': ('Poppins-SemiBold.ttf', 30, 600, HEADINGS, 0),
    'body': ('Inter.ttf', 24, 500, ASCII, 0),
    'clue_small': ('Inter.ttf', 20, 500, ' 0123456789', 20),
    'clue': ('Inter.ttf', 24, 500, ' 0123456789', 24),
}


def build():
    images, image_ids, roles = [], {}, {}
    for name, (file, size, weight, chars, minimum_height) in SPECS.items():
        font = ImageFont.truetype(str(FONTS/file), size)
        features = ['-kern']
        if file == 'Inter.ttf':
            values = []
            for axis in font.get_variation_axes():
                value = weight if axis['name'] == b'Weight' else size
                values.append(max(axis['minimum'], min(axis['maximum'], value)))
            font.set_variation_by_axes(values)
            features.append('tnum')
        bounds = [font.getbbox(ch, anchor='ls', features=features) for ch in chars if ch != ' ']
        baseline = -min(b[1] for b in bounds)
        height = max(minimum_height, baseline + max(b[3] for b in bounds))
        # Extra space is balanced around the actual glyphs, not attached below them.
        baseline += (height - (baseline + max(b[3] for b in bounds))) // 2
        glyphs = {}
        for ch in chars:
            bounds = font.getbbox(ch, anchor='ls', features=features)
            pad = max(0, -bounds[0])
            advance = math.ceil(font.getlength(ch, features=features)) + pad
            canvas = Image.new('L', (max(advance+2, bounds[2]+pad+2), height), 255)
            ImageDraw.Draw(canvas).text((pad, baseline), ch, font=font, fill=0,
                                        anchor='ls', features=features)
            bitmap = canvas.point(lambda v: 0 if v < 128 else 255).convert('1')
            box = Image.eval(bitmap.convert('L'), lambda v: 255-v).getbbox()
            if box is None:
                glyphs[ord(ch)] = [advance, 0, 0, 0]
                continue
            advance = max(advance, box[2])
            glyph = bitmap.crop(box)
            out = BytesIO()
            glyph.save(out, format='PNG', optimize=True)
            raw = out.getvalue()
            if raw not in image_ids:
                image_ids[raw] = len(images)+1
                images.append({'width': glyph.width, 'height': glyph.height, 'png': raw.hex()})
            glyphs[ord(ch)] = [advance, box[0], box[1], image_ids[raw]]
            assert box[2] <= advance and box[3] <= height
        roles[name] = {'name': file.removesuffix('.ttf'), 'size': size,
                       'weight': weight, 'line_height': height, 'glyphs': glyphs}
    lines = ['-- Generated by scripts/make_game_fonts.py. Do not edit.',
             '-- Source licenses: assets/fonts/game-ui/*-OFL.txt', 'return {images={']
    for image in images:
        lines.append('  {' + f'{image["width"]},{image["height"]},"{image["png"]}"' + '},')
    lines.append('},roles={')
    for name, role in roles.items():
        lines.append(f'  {name}={{name={json.dumps(role["name"])},line_height={role["line_height"]},glyphs={{')
        for code, glyph in role['glyphs'].items():
            lines.append(f'    [{code}]={{{",".join(map(str, glyph))}}},')
        lines.append('  }},')
    lines.append('}}')
    source = '\n'.join(lines) + '\n'
    pixels = sum(i['width']*i['height'] for i in images)
    report = {
        'images': len(images), 'decoded_pixels': pixels,
        'decoded_rgb_bytes': pixels*3, 'png_bytes': sum(len(i['png'])//2 for i in images),
        'lua_bytes': len(source.encode()),
        'roles': {name: {k:v for k,v in role.items() if k != 'glyphs'} for name,role in roles.items()},
        'source_sha256': {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                          for p in sorted(FONTS.glob('*.ttf'))},
    }
    assert len(images) <= 384 and pixels*3 <= 256*1024, 'font cache exceeds the memory budget'
    assert len(source.encode()) < 128*1024, 'font source is too large'
    return source, report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source, report = build()
    target = ROOT/'shared/font_data.lua'
    metadata = ROOT/'shared/font-metrics.json'
    licenses = ('Poppins / Inter bitmap glyphs\n\n'
                'Sources: https://github.com/google/fonts/tree/main/ofl/poppins\n'
                'https://github.com/google/fonts/tree/main/ofl/inter\n\n'
                + (FONTS/'Poppins-OFL.txt').read_text()+'\n\n'
                + (FONTS/'Inter-OFL.txt').read_text())
    assert ']==]' not in licenses
    license_source = '-- Bundled font notices and SIL Open Font License texts.\nreturn [==[\n'+licenses+'\n]==]\n'
    license_target = ROOT/'shared/font_license.lua'
    if args.check:
        assert target.read_text() == source, 'Run scripts/make_game_fonts.py'
        assert json.loads(metadata.read_text()) == report, 'Regenerate font metrics'
        assert license_target.read_text() == license_source, 'Regenerate font notices'
    else:
        target.write_text(source)
        metadata.write_text(json.dumps(report, indent=2)+'\n')
        license_target.write_text(license_source)
    print(f'Game fonts: {report["images"]} PNGs, {report["decoded_pixels"]} decoded pixels, '
          f'{report["lua_bytes"]} Lua bytes; ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
