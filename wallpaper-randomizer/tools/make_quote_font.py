#!/usr/bin/env python3
"""Bake Inter SemiBold into rotated 1-bit PNG glyphs for the sleep-screen quotes.

The Licorice canvas has no rotated text, and the wallpaper is viewed in
landscape (native 480x800 portrait turned clockwise). Each glyph is rendered
upright in landscape, thresholded to 1 bit, cropped to its ink and rotated
90 degrees counter-clockwise so it lands upright on the native framebuffer.
Lua only decodes the PNGs a quote needs; no TTF is loaded on the reader.

Writes app/quote_font.lua. Run from anywhere:
    python3 wallpaper-randomizer/tools/make_quote_font.py [--check]
"""
import argparse
from io import BytesIO
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
# The game family's Inter (SIL OFL); a heavy plain sans reads best on e-ink.
FONT = ROOT.parent / 'assets/fonts/game-ui/Inter.ttf'
LICENSE = ROOT.parent / 'assets/fonts/game-ui/Inter-OFL.txt'
OUT = ROOT / 'app/quote_font.lua'
THRESHOLD = 110  # of 255 coverage; slightly bold so hairlines survive 1-bit
ASCII = [chr(c) for c in range(33, 127)]
EXTRA = ['“', '”', '‘', '’', '—', '–', '…']
# role: (size px, weight, line height px)
ROLES = {
    'quote': (30, 600, 39),
    'author': (22, 500, 29),
}


def load(size, weight):
    font = ImageFont.truetype(str(FONT), size, layout_engine=ImageFont.Layout.BASIC)
    axes = []
    for axis in font.get_variation_axes():
        name = axis['name'].decode() if isinstance(axis['name'], bytes) else axis['name']
        axes.append(weight if name == 'Weight' else size if name == 'Optical size' else axis['default'])
    font.set_variation_by_axes(axes)
    return font


def glyph(font, ch):
    pad = font.size
    canvas = Image.new('L', (font.size * 3, font.size * 3), 0)
    ImageDraw.Draw(canvas).text((pad, 2 * pad), ch, font=font, fill=255, anchor='ls')
    ink = canvas.point(lambda p: 255 if p >= THRESHOLD else 0)
    box = ink.getbbox()
    advance = round(font.getlength(ch), 2)
    if not box:
        return advance, None
    left, top, right, bottom = box
    crop = ink.crop(box).point(lambda p: 0 if p else 255).convert('1')  # black ink on white
    native = crop.rotate(90, expand=True)  # landscape -> native portrait framebuffer
    data = BytesIO()
    native.save(data, 'PNG', optimize=True)
    return advance, (left - pad, top - 2 * pad, right - left, bottom - top, data.getvalue())


def build():
    images, lines = [], []
    lines.append('-- Generated by tools/make_quote_font.py. Do not edit.')
    lines.append('-- Inter, SIL Open Font License 1.1: assets/fonts/game-ui/Inter-OFL.txt')
    lines.append('-- glyph = {advance, landscape dx, dy (from baseline), w, h, image index}')
    lines.append('return {roles={')
    for role, (size, weight, line_height) in ROLES.items():
        font = load(size, weight)
        ascent, descent = font.getmetrics()
        entries = ['[32]={%s}' % round(font.getlength(' '), 2)]
        for ch in ASCII + EXTRA:
            advance, ink = glyph(font, ch)
            if ink is None:
                entries.append('%s={%s}' % (lua_key(ch), advance))
                continue
            dx, dy, w, h, png = ink
            images.append(png)
            key = ch if ord(ch) < 128 else ch.encode('utf-8')
            entries.append('[%s]={%s,%d,%d,%d,%d,%d}' % (
                ord(ch) if ord(ch) < 128 else '"' + ''.join('\\%03d' % b for b in key) + '"',
                advance, dx, dy, w, h, len(images)))
        lines.append(' %s={line=%d,ascent=%d,glyphs={%s}},' % (role, line_height, ascent, ','.join(entries)))
    lines.append('},images={')
    for png in images:
        lines.append(' "%s",' % ''.join('\\%03d' % b if (b < 32 or b > 126 or b in (34, 92)) else chr(b) for b in png))
    lines.append('}}')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if app/quote_font.lua is stale')
    args = parser.parse_args()
    assert LICENSE.is_file(), 'Inter OFL text must ship with the font'
    text = build()
    if args.check:
        if OUT.read_text(encoding='ascii') != text:
            raise SystemExit('app/quote_font.lua is stale; rerun tools/make_quote_font.py')
        print('quote_font.lua up to date')
        return
    OUT.write_text(text, encoding='ascii')
    print('%s: %d bytes' % (OUT.relative_to(ROOT), len(text.encode('latin-1'))))


if __name__ == '__main__':
    main()
